#!/usr/bin/env node
/* -------------------------------------------------------------------------
 * Regenerates src/assets/CarRigs.ts from build/cars/<id>.report.json — the
 * tail of the asset pipeline (optimize-cars measures, this emits). Exists so
 * the rig table can never drift from the committed GLBs by hand-pasting: the
 * old copy-paste workflow is how a stale caliperColor and mislabelled L/R
 * hubs survived review (PR #21).
 *
 *   npm run optimize-cars && npm run emit-rigs
 *
 * The interface definition lives here (it IS the pipeline's data contract);
 * TS compilation catches any consumer disagreement.
 * -------------------------------------------------------------------------- */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const REPORTS = join(ROOT, 'build/cars')
const OUT = join(ROOT, 'src/assets/CarRigs.ts')
const ORDER = ['r34', '930', 's15', 'centenario', 'terzo', 'carrera']

const num = (v) => {
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`non-finite ${v}`)
    return String(v)
  }
  if (Array.isArray(v)) return `[${v.map(num).join(', ')}]`
  throw new Error(`unexpected rig value ${JSON.stringify(v)}`)
}

const blocks = []
for (const id of ORDER) {
  const report = JSON.parse(readFileSync(join(REPORTS, `${id}.report.json`), 'utf8'))
  const r = report.rig
  for (const f of ['wheelRadius', 'wheelPos', 'groundClearance', 'bakedPaint', 'lampGlow', 'lampZ', 'logoAnchor', 'nitroAnchor'])
    if (r[f] === undefined) throw new Error(`${id}: rig missing ${f} — rerun optimize-cars (stale report?)`)
  if ('caliperColor' in r) throw new Error(`${id}: report still carries caliperColor — rerun optimize-cars`)
  blocks.push([
    `  ${JSON.stringify(id)}: {`,
    `    wheelRadius: ${num(r.wheelRadius)},`,
    `    wheelPos: ${num(r.wheelPos)},`,
    `    groundClearance: ${num(r.groundClearance)}, bakedPaint: ${r.bakedPaint}, lampGlow: ${r.lampGlow},`,
    `    lampZ: ${num(r.lampZ)},`,
    `    logoAnchor: ${num(r.logoAnchor)}, nitroAnchor: ${num(r.nitroAnchor)},`,
    '  },',
  ].join('\n'))
}

writeFileSync(OUT, `import type { CarId } from '../vehicles/CarSpecs'

/**
 * Per-car runtime rig table for the real-model GLBs (spec §5, Task 4 output).
 * GENERATED by scripts/emit-rigs.mjs from build/cars/<id>.report.json —
 * never hand-edit: rerun \`npm run optimize-cars && npm run emit-rigs\`.
 */
export interface CarRig {
  /** [fl, fr, rl, rr] metres — per-corner visual/spin radius (tyres may differ per corner) */
  wheelRadius: [number, number, number, number]
  /** [fl, fr, rl, rr] hub centres in MODEL space (nose convention: −z forward, world −x = the car's left) */
  wheelPos: [[number, number, number], [number, number, number], [number, number, number], [number, number, number]]
  /** body min-Y when parked on the wheels (m); negative = splitter dips below road */
  groundClearance: number
  /** true → no paint-* materials in the GLB, garage swatches keep author colours */
  bakedPaint: boolean
  /** add emissive glow planes over baked lamp textures */
  lampGlow: boolean
  /** world z of the head-/brake-light glow planes (measured body face, pushed outboard) */
  lampZ: [front: number, rear: number]
  /** rear badge decal position (tail side, +z; measured tail face + 20 mm) */
  logoAnchor: [number, number, number]
  /** nitro flame origins, [left, right], at the tail (+z) */
  nitroAnchor: [[number, number, number], [number, number, number]]
}

export const CAR_RIGS: Record<CarId, CarRig> = {
${blocks.join('\n')}
}
`)
console.log(`[rigs] wrote ${OUT.replace(ROOT, '')} for ${ORDER.join(', ')}`)
